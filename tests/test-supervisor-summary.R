source(file.path('..','app','supervisor.R'),local=TRUE)
test_that('plain summary distinguishes overlapping signals and management goals', {
  m <- data.frame(individual_signal=c(FALSE,TRUE,TRUE),variation_signal=c(FALSE,TRUE,FALSE))
  service <- data.frame(goal=10,within_goal=1/3,n=3)
  s <- supervisor_plain_summary(m,TRUE,'approved',c(FALSE,TRUE,TRUE),service)
  expect_match(s$history,'2 of 3 completed records exceed',fixed=TRUE)
  expect_match(s$history,'1 show an unusually large change',fixed=TRUE)
  expect_match(s$target,'2 of 3 records',fixed=TRUE)
  expect_match(s$target,'overlap',fixed=TRUE)
  expect_match(s$goal,'33% of 3',fixed=TRUE)
  expect_match(s$action,'do not establish a cause',fixed=TRUE)
  disabled <- supervisor_plain_summary(m,FALSE,'baseline requires review',rep(NA,3),data.frame())
  expect_match(disabled$history,'Historical signals unavailable',fixed=TRUE)
  expect_match(disabled$history,'baseline requires review',fixed=TRUE)
  expect_match(disabled$target,'unavailable',fixed=TRUE)
  expect_match(disabled$goal,'No service goal',fixed=TRUE)
  empty <- supervisor_plain_summary(m[FALSE,],FALSE,'insufficient',logical(),data.frame())
  expect_match(empty$history,'Pending trips are not zero',fixed=TRUE)
  m$individual_signal <- m$variation_signal <- FALSE
  s <- supervisor_plain_summary(m,TRUE,'approved',c(FALSE,NA,NA),service)
  expect_match(s$history,'0 of 3',fixed=TRUE)
  expect_match(s$target,'0 of 1 records',fixed=TRUE)
  expect_match(s$action,'no signal does not prove acceptable',fixed=TRUE)
})
