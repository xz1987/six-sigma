source(file.path('..','app','supervisor.R'),local=TRUE)
test_that('plain summary distinguishes overlapping signals and management goals', {
  m <- data.frame(individual_signal=c(FALSE,TRUE,TRUE),variation_signal=c(FALSE,TRUE,FALSE))
  service <- data.frame(goal=10,within_goal=1/3,n=3)
  s <- supervisor_plain_summary(m,TRUE,'approved',c(FALSE,TRUE,TRUE),service)
  expect_match(s$history,'2 of 3 completed records exceed',fixed=TRUE)
  expect_match(s$history,'1 show an unusually large change',fixed=TRUE)
  expect_match(s$target,'2 of 3 records',fixed=TRUE)
  expect_match(s$target,'overlap',fixed=TRUE)
  expect_match(s$goal,'33% of 3',fixed=TRUE)
  expect_match(s$action,'do not establish a cause',fixed=TRUE)
  disabled <- supervisor_plain_summary(m,FALSE,'baseline requires review',rep(NA,3),data.frame())
  expect_match(disabled$history,'Historical signals unavailable',fixed=TRUE)
  expect_match(disabled$history,'baseline requires review',fixed=TRUE)
  expect_match(disabled$target,'unavailable',fixed=TRUE)
  expect_match(disabled$goal,'No service goal',fixed=TRUE)
  empty <- supervisor_plain_summary(m[FALSE,],FALSE,'insufficient',logical(),data.frame())
  expect_match(empty$history,'Pending trips are not zero',fixed=TRUE)
  m$individual_signal <- m$variation_signal <- FALSE
  s <- supervisor_plain_summary(m,TRUE,'approved',c(FALSE,NA,NA),service)
  expect_match(s$history,'0 of 3',fixed=TRUE)
  expect_match(s$target,'0 of 1 records',fixed=TRUE)
  expect_match(s$action,'no signal does not prove acceptable',fixed=TRUE)
})

test_that('history summary describes subgroup means and individual goals separately', {
  d <- data.frame(signal=c(FALSE,TRUE,NA))
  goal <- data.frame(n=12,p90=15,within_goal=.75,goal=12)
  s <- supervisor_history_summary(d,goal,'week',TRUE,'approved',4)
  expect_match(s$history,'1 of 2 assessable weekly means',fixed=TRUE)
  expect_match(s$history,'not counts',fixed=TRUE)
  expect_match(s$goal,'p90 is 15.0 minutes; 75% of 12',fixed=TRUE)
  expect_match(s$coverage,'4 current-day responses are excluded',fixed=TRUE)
  expect_match(s$coverage,'distribution chart summarizes daily means',fixed=TRUE)
  expect_match(s$action,'not prospective monitoring',fixed=TRUE)
  s <- supervisor_history_summary(d,goal,'day',FALSE,'baseline requires review',0)
  expect_match(s$history,'unavailable: baseline requires review',fixed=TRUE)
  d$signal <- NA
  s <- supervisor_history_summary(d,goal,'day',TRUE,'degenerate baseline',0)
  expect_match(s$history,'unavailable: degenerate baseline',fixed=TRUE)
  goal$n <- 0
  s <- supervisor_history_summary(data.frame(),goal,'day',TRUE,'approved',0)
  expect_match(s$history,'No completed subgroups',fixed=TRUE)
  expect_match(s$goal,'No completed individual responses',fixed=TRUE)
  goal$n <- 12;goal$goal <- NA_real_
  s <- supervisor_history_summary(data.frame(signal=FALSE),goal,'day',TRUE,'approved',0)
  expect_match(s$goal,'no service goal is configured',fixed=TRUE)
})

test_that('Patterns summary follows distinct chart scopes and retains sparse weather', {
  d <- data.frame(zone=c('Astoria','Astoria','Flushing','Astoria'),
    call_priority=c('High','High','High','Low'),weather_condition=c('Dry','Unknown','Rain','Dry'),
    response_minutes=c(8,12,20,99),
    dispatch_time=qc_parse_time(rep('2026-10-17T12:00:00Z',4)))
  s <- supervisor_patterns_summary(d,'Astoria','High')
  expect_match(s$scope,'3 completed records across all zones',fixed=TRUE)
  expect_match(s$scope,'2 records in Astoria / High',fixed=TRUE)
  expect_match(s$zones,'Astoria: median 10.0 min (n=2)',fixed=TRUE)
  expect_match(s$zones,'Flushing: median 20.0 min (n=1)',fixed=TRUE)
  expect_match(s$weather,'Unknown: median 12.0 min (n=1)',fixed=TRUE)
  expect_false(grepl('Rain:',s$weather,fixed=TRUE))
  expect_match(s$time,'1 of 168',fixed=TRUE)
  expect_match(s$time,'10.0 to 10.0 minutes',fixed=TRUE)
  expect_match(s$action,'not proof of a weather effect',fixed=TRUE)
  empty <- supervisor_patterns_summary(d,'Jamaica','High')
  expect_match(empty$weather,'No completed records',fixed=TRUE)
  expect_match(empty$time,'No populated',fixed=TRUE)
  empty <- supervisor_patterns_summary(d[FALSE,],'Astoria','High')
  expect_match(empty$zones,'No completed records',fixed=TRUE)
})
